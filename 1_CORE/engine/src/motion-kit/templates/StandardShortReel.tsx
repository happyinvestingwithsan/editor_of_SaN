import React from "react";
import { Audio, staticFile, useCurrentFrame } from "remotion";
import { MobileSplitLayout } from "../layouts/MobileSplitLayout";
import { KineticSubtitles, SubtitleBlock } from "../modules/KineticSubtitles";
import { SFXPlayer, SFXCue } from "../modules/SFXPlayer";

export interface ReelStageConfig {
  id: string;
  startFrame: number;
  endFrame: number;
  mode?: "standard_split" | "full_graphics_takeover" | "facecam_punch";
  component: React.ReactNode;
}

export interface StandardShortReelProps {
  /** Relative path inside public/ of video proxy (e.g. "video/jio_reel_fast.mp4") */
  videoProxySrc?: string;
  /** Relative path inside public/ of master 48kHz audio (e.g. "audio/jio_reel_audio.wav") */
  audioSrc?: string;
  /** Array of timed motion graphic stages */
  stages: ReelStageConfig[];
  /** Subtitle blocks generated by Faster-Whisper */
  captionBlocks?: SubtitleBlock[];
  /** Sound design trigger cues */
  sfxCues?: SFXCue[];
}

/**
 * StandardShortReel:
 * The canonical plug-and-play template for 9:16 viral financial shorts.
 * Consistently renders facecam, subtitles, SFX, and switches motion stages.
 */
export const StandardShortReel: React.FC<StandardShortReelProps> = ({
  videoProxySrc,
  audioSrc,
  stages = [],
  captionBlocks = [],
  sfxCues = [],
}) => {
  const frame = useCurrentFrame();

  // Find active stage
  const activeStage = stages.find(
    (s) => frame >= s.startFrame && frame <= s.endFrame
  );

  const isTakeover = activeStage?.mode === "full_graphics_takeover";
  const isPunch = activeStage?.mode === "facecam_punch";

  return (
    <MobileSplitLayout
      videoSrc={videoProxySrc ? staticFile(videoProxySrc) : undefined}
      audioTrack={
        <>
          {audioSrc && <Audio src={staticFile(audioSrc)} volume={1.0} />}
          {sfxCues.length > 0 && <SFXPlayer cues={sfxCues} />}
        </>
      }
      isFullScreenTakeover={isTakeover}
      isFacecamPunch={isPunch}
      captionSlot={
        captionBlocks.length > 0 ? (
          <KineticSubtitles blocks={captionBlocks} />
        ) : undefined
      }
    >
      {activeStage?.component}
    </MobileSplitLayout>
  );
};
